const predictionStorageKey = 'raif-predictions-deck-v2';
const predictionCatalog = predictions.join('|').split('').reduce(
  (hash, character) => Math.imul(hash ^ character.charCodeAt(0), 16777619),
  2166136261
) >>> 0;
let predictionDeck = { catalog: predictionCatalog, remaining: [], last: -1 };

function loadPredictionDeck() {
  try {
    const saved = JSON.parse(localStorage.getItem(predictionStorageKey));
    if (saved && saved.catalog === predictionCatalog &&
        Array.isArray(saved.remaining) && saved.remaining.length <= predictions.length &&
        Number.isInteger(saved.last) && saved.last >= 0 && saved.last < predictions.length &&
        saved.remaining.every(index => Number.isInteger(index) && index >= 0 && index < predictions.length) &&
        new Set(saved.remaining).size === saved.remaining.length &&
        !saved.remaining.includes(saved.last)) {
      predictionDeck = saved;
    }
  } catch {
    // Якщо сховище недоступне, колода працює в пам’яті поточної сторінки.
  }
}

