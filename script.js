function pickDifferent(length, previous) {
  // Рівномірний вибір серед усіх варіантів, крім попереднього.
  if (length < 2) return 0;
  if (previous < 0) return Math.floor(Math.random() * length);
  const index = Math.floor(Math.random() * (length - 1));
  return index >= previous ? index + 1 : index;
}


// Перемішана колода: усі 200 текстів видаються один раз за цикл.
// Стан зберігається лише в браузері, щоб оновлення сторінки не скидало історію.
const predictionStorageKey = 'raif-predictions-deck-v2';
const predictionCatalog = predictions.join('|').split('').reduce(
  (hash, character) => Math.imul(hash ^ character.charCodeAt(0), 16777619),
  2166136261
) >>> 0;
let predictionDeck = { catalog: predictionCatalog, remaining: [], last: -1 };

function loadPredictionDeck() {
  try {
    const saved = JSON.parse(localStorage.getItem(predictionStorageKey));
    if (saved && saved.catalog === predictionCatalog &&
        Array.isArray(saved.remaining) && saved.remaining.length <= predictions.length &&
        Number.isInteger(saved.last) && saved.last >= 0 && saved.last < predictions.length &&
        saved.remaining.every(index => Number.isInteger(index) && index >= 0 && index < predictions.length) &&
        new Set(saved.remaining).size === saved.remaining.length &&
        !saved.remaining.includes(saved.last)) {
      predictionDeck = saved;
    }
  } catch {
    // Якщо сховище недоступне, колода працює в пам’яті поточної сторінки.
  }
}

function nextPredictionIndex() {
  loadPredictionDeck();
  const deck = predictionDeck.remaining;
  if (deck.length === 0) {
    deck.push(...predictions.map((_, index) => index));
    // Перемішування Фішера — Єйтса.
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    // Перша картка нового циклу не повторює останню картку попереднього.
    const lastIndex = deck.length - 1;
    if (deck.length > 1 && deck[lastIndex] === predictionDeck.last) {
      const swapIndex = Math.floor(Math.random() * lastIndex);
      [deck[lastIndex], deck[swapIndex]] = [deck[swapIndex], deck[lastIndex]];
    }
  }
  predictionDeck.last = deck.pop();
  try {
    localStorage.setItem(predictionStorageKey, JSON.stringify(predictionDeck));
  } catch {
    // Блокування localStorage не заважає показувати передбачення.
  }
  return predictionDeck.last;
}

button.addEventListener('click', () => {
  // Приблизно кожен п’ятий результат — цитата.
  const isQuote = Math.random() < 0.2;
  if (isQuote) {
    previousQuote = pickDifferent(quotes.length, previousQuote);
    const quote = quotes[previousQuote];
    fortune.textContent = '«' + quote.text + '»';
    attribution.textContent = quote.author + ' · ' + quote.source;
    attribution.hidden = false;
    kind.textContent = 'СЛОВА, ЩО НАДИХАЮТЬ';
  } else {
    previousPrediction = nextPredictionIndex();
    fortune.textContent = predictions[previousPrediction];
    attribution.textContent = '';
    attribution.hidden = true;
    kind.textContent = 'ТВОЄ ПЕРЕДБАЧЕННЯ';
  }
  label.textContent = 'Ще одне';
  result.classList.remove('reveal');
  void result.offsetWidth;
  result.classList.add('reveal');
});

